export async function seedAllEquipment(shouldClean = false) {
  if (!uri) {
    console.error("[Seed Error] DB_URI is not defined");
    return;
  }
  const client = new MongoClient(uri);
  try {
    await client.connect();
    const db = client.db(dbName);
    const col = db.collection("equipment");

    if (shouldClean) {
      console.log("[Seed] Cleaning existing collection for a clean slate of 48+ products...");
      await col.deleteMany({});
      await col.insertMany(ALL_48_EQUIPMENT);
      console.log(`[Seed] Successfully inserted all ${ALL_48_EQUIPMENT.length} unique equipment products!`);
    } else {
      let upsertCount = 0;
      for (const item of ALL_48_EQUIPMENT) {
        await col.updateOne(
          { title: item.title },
          { $set: item },
          { upsert: true }
        );
        upsertCount++;
      }
      console.log(`[Seed] Upserted ${upsertCount} products into database.`);
    }

    const total = await col.countDocuments();
    console.log(`[Total Equipment in DB] Now contains: ${total} items.`);
  } catch (err) {
    console.error("[Seed Error]", err);
  } finally {
    await client.close();
  }
}

// Only execute when run directly from CLI (never when imported by server.js or index.js)
if (process.argv[1]?.endsWith("seedAllEquipment.js")) {
  const shouldClean = process.argv.includes("--clean");
  seedAllEquipment(shouldClean).then(() => process.exit(0));
}
